fn make_color(r: u16, g: u16, b: u16) -> Color {
    return Color(r | (g << 5) | (b << 10));
}

#[unsafe(no_mangle)]
extern "C" fn main() -> ! {
    logger::init_logger();

    RUST_IRQ_HANDLER.write(Some(irq_handler));
    DISPSTAT.write(DisplayStatus::new().with_irq_vblank(true));
    IE.write(IrqBits::VBLANK);
    IME.write(true);

    VBlankIntrWait();

    let no_display = ObjAttr0::new().with_style(ObjDisplayStyle::NotDisplayed);
    OBJ_ATTR0.iter().for_each(|va| va.write(no_display));

    DISPCNT.write(
        DisplayControl::new()
            .with_video_mode(VideoMode::_0)
            .with_show_obj(false)
            .with_show_bg0(true)
            .with_show_bg1(true), // .with_obj_vram_1d(true)
                                  // .with_show_obj(true),
    );

    unsafe {
        copy_nonoverlapping(
            bg_pal.as_ptr(),
            BG_PALETTE.as_usize() as *mut u16,
            bg_pal.len(),
        );

        copy_nonoverlapping(
            bg_tiles.as_ptr(),
            CHARBLOCK0_8BPP.as_usize() as *mut u16,
            bg_tiles.len(),
        );
        copy_nonoverlapping(
            bg_check.as_ptr(),
            TEXT_SCREENBLOCKS.get_frame(1).unwrap().as_usize() as *mut u16,
            bg_check.len(),
        );
    }

    for i in 0..32 {
        BG_PALETTE
            .index(bg_pal.len() + i)
            .write(make_color(i as u16, i as u16, i as u16));
    }

    let mut tile: [u8; 64] = core::array::repeat(0);
    for i in 0..32 {
        let val = (bg_pal.len() + i) as u8;
        for j in 0..64 {
            tile[j] = val;
        }
        unsafe {
            copy_nonoverlapping(
                tile.as_ptr(),
                CHARBLOCK1_8BPP.index(i).as_usize() as *mut u8,
                tile.len(),
            );
        }
    }
    let mut screen_block: [u16; 1024] = core::array::repeat(0);
    for i in 0..32 {
        for j in 0..32 {
            screen_block[i * 32 + j] = j as u16;
        }
    }
    unsafe {
        copy_nonoverlapping(
            screen_block.as_ptr(),
            TEXT_SCREENBLOCKS.get_frame(2).unwrap().as_usize() as *mut u16,
            screen_block.len(),
        );
    }

    let mut gradient_screenblock = 2;

    BG0CNT.write(
        BackgroundControl::new()
            .with_size(0)
            .with_screenblock(1)
            .with_bpp8(true)
            .with_charblock(0),
    );
    BG1CNT.write(
        BackgroundControl::new()
            .with_size(0)
            .with_screenblock(gradient_screenblock)
            .with_bpp8(true)
            .with_charblock(1)
            .with_priority(1),
    );

    let mut bg0hscroll = 0;
    let mut bg1hscroll = 0;
    let mut is_pressed = true;
    let mut last_offscreen_column: u8 = 0;
    loop {
        VBlankIntrWait();

        let k = FRAME_KEYS.read();
        BG0HOFS.write(bg0hscroll);
        BG1HOFS.write(bg1hscroll);
        bg1hscroll = bg1hscroll + 1;
        bg0hscroll = bg0hscroll - 1;
        let offset = offscreen_column_start(bg1hscroll, MapSize::_64);

        if last_offscreen_column != offset {
            last_offscreen_column = offset;
            gba_warning!("Offset offscreen {offset}");
        }

        if k.up() {
            if !is_pressed {
                is_pressed = true;
                gradient_screenblock = gradient_screenblock - 1;
                BG1CNT.write(BG1CNT.read().with_screenblock(gradient_screenblock));
                gba_warning!("Changing screenblock {gradient_screenblock}");
            }
        } else if k.down() {
            if !is_pressed {
                is_pressed = true;
                gradient_screenblock = gradient_screenblock + 1;
                BG1CNT.write(BG1CNT.read().with_screenblock(gradient_screenblock));
                gba_warning!("Changings screenblock {gradient_screenblock}");
            }
        } else {
            is_pressed = false;
        }
    }
}

enum MapSize {
    _32,
    _64,
}

fn offscreen_column_start(hscroll: u16, map_size: MapSize) -> u8 {
    let mask = match map_size {
        MapSize::_32 => 0x1F_u8,
        MapSize::_64 => 0x3F_u8,
    };
    let h = (hscroll & 0x01FF) as u16;
    let right_col = (((h + 240) >> 3) as u8) & mask;
    return right_col;
}
